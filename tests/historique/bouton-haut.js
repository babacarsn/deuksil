const {open, loginAs, goto} = require('./harnais.js');
const chev = (a, b) => a && b && !(a.right <= b.left || b.right <= a.left || a.bottom <= b.top || b.bottom <= a.top);
(async () => { const {b, ctx, p} = await open();
  const cas = async (nom, vp, hash, cni) => {
    await p.setViewportSize(vp);
    if (cni) await loginAs(p, cni); await goto(p, hash); await p.waitForTimeout(300);
    const a0 = await p.evaluate(() => document.querySelector('.haut').classList.contains('on'));
    await p.evaluate(() => scrollTo(0, document.documentElement.scrollHeight)); await p.waitForTimeout(700);
    const st = await p.evaluate(() => { const r = e => e && e.getBoundingClientRect().width ? e.getBoundingClientRect().toJSON() : null;
      return {on: document.querySelector('.haut').classList.contains('on'), h: r(document.querySelector('.haut')), ai: r(document.querySelector('.ai-fab')), tab: r(document.querySelector('.tabbar')), y: scrollY, off: document.querySelector('.haut-prog').style.strokeDashoffset}; });
    await p.screenshot({path: __dirname + `/haut-${nom}.png`});
    await p.click('.haut'); await p.waitForTimeout(250);
    const mi = await p.evaluate(() => scrollY); await p.waitForTimeout(1200);
    const fin = await p.evaluate(() => [scrollY, document.querySelector('.haut').classList.contains('on')]);
    console.log(nom, 'avant', a0, 'bas:', st.on, 'y', st.y, 'anneau', Math.round(st.off), 'chev ai', chev(st.h, st.ai), 'chev tab', chev(st.h, st.tab), 'haut', JSON.stringify(st.h && [Math.round(st.h.x), Math.round(st.h.y)]), '| glisse', mi, '→ fin', fin);
  };
  await cas('accueil-desk', {width: 1280, height: 800}, '#/');
  await cas('accueil-mob', {width: 390, height: 800}, '#/');
  const cni = await p.evaluate(() => DB.getData(DB.K.users).find(u => u.role === 'owner' && !u.member).cni);
  await loginAs(p, cni); await goto(p, '#/owner/properties'); await p.setViewportSize({width: 390, height: 760});
  await p.evaluate(() => scrollTo(0, 99999)); await p.waitForTimeout(600);
  console.log('autre page : bouton masqué', !(await p.evaluate(() => document.querySelector('.haut').classList.contains('on'))));
  console.log('erreurs', p.errs); await b.close(); })();
